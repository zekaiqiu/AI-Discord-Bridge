/**
 * Minimal homegrown i18n. Translations live as a single dict keyed by
 * language code; `useT()` returns a `t(key, vars?)` lookup function
 * that reads the current language from React context.
 *
 * Why no i18next:
 *  - ~50 strings, no plural rules complex enough to need ICU.
 *  - Saves ~5KB on the bundle (already 1.3MB before compression).
 *  - Lookup is O(1), context propagation is React's default.
 *
 * Pluralisation: when a key needs different forms for 1 vs N, we
 * split into ".one" / ".other" suffixes and select in the call site.
 *
 * Coverage: Sidebar + Composer + SettingsDashboard are fully
 * translated. Thread + Agents + Usage stay English for now (less
 * visible / admin-only / heavily code-content).
 */
